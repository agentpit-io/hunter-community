-- 自选股加「买入均价」· 2026-09-01
--
-- 为什么:只有 shares 时,交易成本页只能算出"买卖一趟花 27.5 元" ——
-- 用户看完仍不知道这 27.5 元疼不疼。有了买入价才能算出三个真正有用的数:
--   · 净盈亏   = 毛盈亏 − 买入已付成本 − 卖出将付成本
--   · 保本价   = 涨到多少才真回本(把往返成本折进价格)
--   · 成本吃掉了盈利的百分之多少
-- 这正是评委要的「毛 vs 净」框架,只不过落在用户自己的持仓上。
--
-- 不复用 /portfolio:那是另一套建仓批次/加仓减仓的模型,这里只要一个均价。
-- NULL = 用户没填(和 0 区分开 —— 0 元买入是无意义的,不该当成"填了")
ALTER TABLE stocks
  ADD COLUMN IF NOT EXISTS avg_cost NUMERIC(12,4);

COMMENT ON COLUMN stocks.avg_cost IS '买入均价 · NULL 表示未填 · 供 /cost 算净盈亏与保本价';
